"""Generates Verse tuning constants from data/tuning.csv (adapted from Casino Royale's CSV-driven tuning).

Verse can't read CSV files at runtime, so the numbers are compiled in: this script writes one Verse file of
module-scope constants. Never edit that file by hand. Edit the CSV (or let the balance simulator write it),
re-run this script, then build Verse and run the self-test.

  py tools/gen_tuning.py data/tuning.csv <path to the project's Verse folder>/tuning.verse
  py tools/gen_tuning.py data/tuning.csv - --check <tuning.verse>   # exit 1 if the file is out of date

CSV columns: name,type,value,note   (type: int, float, logic, string)
"""

import csv
import os
import re
import sys

NAME = re.compile(r"^[A-Z][A-Za-z0-9]*$")  # Verse style: PascalCase for constants


def verse_value(kind, raw, name):
    raw = raw.strip()
    if kind == "int":
        return str(int(raw))
    if kind == "float":
        value = float(raw)
        text = repr(value)
        return text if ("." in text or "e" in text) else text + ".0"  # Verse floats need a decimal point
    if kind == "logic":
        if raw.lower() not in ("true", "false"):
            raise ValueError("%s: logic must be true or false, got %r" % (name, raw))
        return raw.lower()
    if kind == "string":
        return '"%s"' % raw.replace("\\", "\\\\").replace('"', '\\"').replace("{", "\\{").replace("}", "\\}")
    raise ValueError("%s: unknown type %r (use int, float, logic, string)" % (name, kind))


def generate(csv_path):
    lines = [
        "# GENERATED by tools/gen_tuning.py from %s. Do not edit by hand." % os.path.basename(csv_path),
        "# Edit the CSV (or re-run the simulator that writes it), re-run the generator, build Verse, run the self-test.",
        "",
    ]
    seen = set()
    with open(csv_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            name, kind = row["name"].strip(), row["type"].strip()
            if not NAME.match(name):
                raise ValueError("%s: names must be PascalCase letters and digits" % name)
            if name in seen:
                raise ValueError("%s: duplicate name" % name)
            seen.add(name)
            note = (row.get("note") or "").strip()
            if note:
                lines.append("# " + note)
            lines.append("%s:%s = %s" % (name, kind, verse_value(kind, row["value"], name)))
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    text = generate(argv[0])
    if len(argv) >= 4 and argv[2] == "--check":
        with open(argv[3], encoding="utf-8") as f:
            if f.read() != text:
                print("OUT OF DATE: %s does not match %s; re-run the generator" % (argv[3], argv[0]))
                return 1
        print("up to date")
        return 0
    if argv[1] == "-":
        sys.stdout.write(text)
    else:
        with open(argv[1], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s (%d constants)" % (argv[1], sum(1 for l in text.splitlines() if ":" in l and not l.startswith("#"))))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
